use xet_cdc::{ChunkHash, hash_chunk};

#[test]
fn chunk_hash_is_exactly_32_bytes() {
    assert_eq!(std::mem::size_of::<ChunkHash>(), 32);
}

#[test]
fn matches_known_digest_for_empty_chunk() {
    let expected = ChunkHash {
        bytes: [
            0x10, 0x5f, 0x7e, 0x4e, 0x78, 0xcf, 0xf2, 0xe0,
            0x5f, 0x9a, 0x0e, 0x15, 0xaf, 0x84, 0x4f, 0xc3,
            0x15, 0xd9, 0xba, 0xde, 0x16, 0x42, 0x66, 0xf9,
            0x67, 0x0f, 0x87, 0x49, 0x10, 0x74, 0x4d, 0x36,
        ],
    };

    assert_eq!(hash_chunk(&[]), expected);
}

#[test]
fn matches_known_digest_for_hello() {
    let expected = ChunkHash {
        bytes: [
            0x0b, 0x05, 0x98, 0xd9, 0x12, 0xba, 0x76, 0x90,
            0x3e, 0x94, 0x0f, 0x77, 0xbf, 0xc8, 0x95, 0x9c,
            0xb7, 0x82, 0x0a, 0x49, 0xc7, 0x55, 0xad, 0x6c,
            0xc2, 0xc2, 0x05, 0x2a, 0x2a, 0x58, 0xf1, 0x6c,
        ],
    };

    assert_eq!(hash_chunk(b"hello"), expected);
}

#[test]
fn matches_known_digest_for_all_byte_values() {
    let expected = ChunkHash {
        bytes: [
            0x95, 0xc2, 0xfb, 0xa7, 0x8e, 0x22, 0x57, 0x9f,
            0x96, 0x3f, 0x0f, 0xde, 0xce, 0xcd, 0x01, 0x9b,
            0xf3, 0x52, 0x23, 0x44, 0xcc, 0xcf, 0xf0, 0x88,
            0x22, 0x02, 0xe2, 0xdf, 0xa9, 0xd4, 0x20, 0xb0,
        ],
    };

    let data: Vec<u8> = (0u8..=u8::MAX).collect();

    assert_eq!(hash_chunk(&data), expected);
}

#[test]
fn distinguishes_different_chunks() {
    assert_ne!(hash_chunk(b"hello"), hash_chunk(b"hellp"));
}
